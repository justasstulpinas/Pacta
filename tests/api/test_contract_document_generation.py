def test_pdf_endpoint_paginates_long_contract(long_contract_document_ctx):
    client, submission_id = long_contract_document_ctx

    response = client.get(f"/contracts/submissions/{submission_id}/pdf")
    assert response.status_code == 200
    assert response.headers["content-type"] == "application/pdf"
    assert len(response.content) > 0

    html_response = client.get(f"/contracts/submissions/{submission_id}/document")
    assert html_response.status_code == 200
    html = html_response.json()["html"]

    rendered_document = HTML(string=html).render()
    assert len(rendered_document.pages) > 1


